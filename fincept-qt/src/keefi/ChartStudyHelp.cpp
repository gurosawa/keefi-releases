QString chartStudyName(const QString& id){
    // Keep source labels stable, but translate only the requested name each time.
    // Caching translated strings would miss a translator installed at runtime.
    static const QMap<QString,const char*> names{{"pullback",QT_TRANSLATE_NOOP("QObject","Pullback Zone")},{"whales",QT_TRANSLATE_NOOP("QObject","Whales & Reversal")},
        {"similarity",QT_TRANSLATE_NOOP("QObject","Similarity · Historical Comparison")},{"cloud",QT_TRANSLATE_NOOP("QObject","Trend Cloud")},{"volume",QT_TRANSLATE_NOOP("QObject","Volume")},{"stock_flow",QT_TRANSLATE_NOOP("QObject","Stock Flow & Volume")},{"ma",QT_TRANSLATE_NOOP("QObject","Moving Averages")},{"bb",QT_TRANSLATE_NOOP("QObject","Bollinger Bands")},
        {"rsi","RSI"},{"macd","MACD"},{"levels",QT_TRANSLATE_NOOP("QObject","Price Levels")},{"cvd",QT_TRANSLATE_NOOP("QObject","Cumulative Volume Delta")},{"oi",QT_TRANSLATE_NOOP("QObject","Open Interest")},
        {"contract",QT_TRANSLATE_NOOP("QObject","Contract Flow")},{"sentiment",QT_TRANSLATE_NOOP("QObject","Futures Sentiment")},{"absorption",QT_TRANSLATE_NOOP("QObject","Absorption")},{"sweep",QT_TRANSLATE_NOOP("QObject","Liquidity Sweep")},
        {"squeeze",QT_TRANSLATE_NOOP("QObject","Volatility Squeeze")},{"adx","ADX"},{"breakout",QT_TRANSLATE_NOOP("QObject","Breakout")},{"low_volume",QT_TRANSLATE_NOOP("QObject","Low Volume Zones")},
        {"strong",QT_TRANSLATE_NOOP("QObject","Strong Reversal")},{"trend",QT_TRANSLATE_NOOP("QObject","Multi-Timeframe Trend")},{"relative_strength",QT_TRANSLATE_NOOP("QObject","BTC Relative Strength")}};
    const auto* name=names.value(id,nullptr);
    if(!name)return {};
    if(id=="rsi"||id=="macd"||id=="adx")return QString::fromLatin1(name);
    return QObject::tr(name);
}
